const fs=require("node:fs");
const html=fs.readFileSync("index.html","utf8");
const script=fs.readFileSync("script.js","utf8");
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
const duplicates=[...new Set(ids.filter((id,index)=>ids.indexOf(id)!==index))];
if(duplicates.length)throw new Error("Duplicate HTML IDs: "+duplicates.join(", "));
const stages=[...html.matchAll(/data-tutorial-step="(\d+)"/g)].map(m=>Number(m[1]));
if(stages.length!==9||stages.some((stage,index)=>stage!==index))throw new Error("Academy must contain nine ordered stages (0–8).");
const match=script.match(/const UI_COPY = ([\s\S]*?);\n\nconst state=/);
if(!match)throw new Error("UI_COPY dictionary is missing.");
const copy=JSON.parse(match[1]);
const keys=[...new Set([...html.matchAll(/data-i18n(?:-aria|-title)?="([^"]+)"/g)].map(m=>m[1]))];
const langStart=script.indexOf("const LANGUAGES = {");
const langEnd=script.indexOf(";\n\nconst UI_COPY =",langStart);
if(langStart<0||langEnd<0)throw new Error("Legacy locale dictionary is missing.");
const langBlock=script.slice(langStart,langEnd);
const enStart=langBlock.indexOf("  en:{");
const idStart=langBlock.indexOf("  id:{");
const msStart=langBlock.indexOf("  ms:{",idStart);
if(enStart<0||idStart<0||msStart<0)throw new Error("English/Indonesian locale fallback is incomplete.");
const legacy={en:langBlock.slice(enStart,idStart),id:langBlock.slice(idStart,msStart)};
for(const locale of ["en","id"])for(const key of keys){
  if(typeof copy[locale]?.[key]==="string"&&copy[locale][key].trim())continue;
  if(!legacy[locale].includes(key+":"))throw new Error("Missing "+locale+" translation: "+key);
}
const headerKeys=["landing.brand.aria","landing.brand.tagline","landing.nav.aria","landing.nav.platform","landing.nav.workflow","landing.nav.academy","landing.nav.openFolder","landing.nav.theme","landing.nav.themeTitle"];
for(const locale of ["en","id"])for(const key of headerKeys)if(typeof copy[locale]?.[key]!=="string")throw new Error("Missing "+locale+" header translation: "+key);
for(const id of ["welcomeScreen","tutorialScreen","newProjectScreen","settingsScreen","appScreen","buildHealthChecks"])if(!ids.includes(id))throw new Error("Missing UI element: "+id);
if(!html.includes("x86_64 · BIOS · GRUB · Multiboot2"))throw new Error("The supported native target must be stated.");
if(!/locale:"id"/.test(script))throw new Error("Bahasa Indonesia must be the default locale.");
if(!/\["auto","Deteksi otomatis"\],\["id","Bahasa Indonesia"\],\["en","English"\]/.test(script))throw new Error("Only complete UI locales should be offered.");
if(!script.includes('$$("[data-i18n-title]")'))throw new Error("Localized title attributes are not handled.");
if(!script.includes('$$("[data-i18n-aria]")'))throw new Error("Localized ARIA attributes are not handled.");
console.log("UI audit passed: "+ids.length+" IDs, nine Academy stages and "+keys.length+" fully covered bilingual interface keys.");
